package travailleurs;
public class Travailleurs {
    private String job;
    private String nom;
    private int age;

    public void Soigneur(String job, String nom, int age) {
        this.job = job;
        this.nom = nom;
        this.age = age;
    }

    public void Nettoyeur(String job, String nom, int age) {
        this.job = job;
        this.nom = nom;
        this.age = age;
    }
}
